# Run from rework/: python tools/bake-rotations.py
# Writes assets/rotations.png and src/content/rotation-frames.ts.
import json
import math

import numpy as np
from PIL import Image

FRAMES = 64
SPRITES = ['hull0', 'tur', 'tur_gun', 'jeep0', 'sol_stand', 'sol_rpg']
SHEET_WIDTH = 2048
# Summed over RGB, out of 765. The same closeness as the edge shader in render/layers/solid.ts, for a fair comparison.
SAME_COLOR = 30


def same(a, b):
    a_solid = a[..., 3] >= 128
    b_solid = b[..., 3] >= 128
    close = np.abs(a[..., :3].astype(np.int32) - b[..., :3].astype(np.int32)).sum(axis=-1) < SAME_COLOR
    return (a_solid & b_solid & close) | (~a_solid & ~b_solid)


def scale2x(image):
    padded = np.pad(image, ((1, 1), (1, 1), (0, 0)))
    center = padded[1:-1, 1:-1]
    up, down = padded[:-2, 1:-1], padded[2:, 1:-1]
    left, right = padded[1:-1, :-2], padded[1:-1, 2:]
    active = ~same(up, down) & ~same(left, right)
    pick = lambda condition, other: np.where((active & condition)[..., None], other, center)
    height, width = center.shape[:2]
    out = np.zeros((height * 2, width * 2, 4), dtype=np.uint8)
    out[0::2, 0::2] = pick(same(left, up), left)
    out[0::2, 1::2] = pick(same(up, right), right)
    out[1::2, 0::2] = pick(same(left, down), left)
    out[1::2, 1::2] = pick(same(down, right), right)
    return out


def bake_frame(big, width, height, pivot_x, pivot_y, angle):
    corners = [(0, 0), (width, 0), (0, height), (width, height)]
    reach = max(math.hypot(x - pivot_x, y - pivot_y) for x, y in corners)
    radius = math.ceil(reach) + 2
    cos, sin = math.cos(angle), math.sin(angle)
    ys, xs = np.mgrid[-radius:radius, -radius:radius] + 0.5
    source_x = np.floor((cos * xs + sin * ys + pivot_x) * 8).astype(np.int32)
    source_y = np.floor((-sin * xs + cos * ys + pivot_y) * 8).astype(np.int32)
    inside = (source_x >= 0) & (source_y >= 0) & (source_x < width * 8) & (source_y < height * 8)
    out = np.zeros((*xs.shape, 4), dtype=np.uint8)
    out[inside] = big[source_y[inside], source_x[inside]]
    out[out[..., 3] < 128] = 0
    solid_y, solid_x = np.nonzero(out[..., 3])
    left, right = solid_x.min(), solid_x.max() + 1
    top, bottom = solid_y.min(), solid_y.max() + 1
    return out[top:bottom, left:right], radius - left, radius - top


def main():
    atlas = np.asarray(Image.open('assets/atlas.png').convert('RGBA'))
    table = json.load(open('assets/atlas.json'))
    baked = {}
    for name in SPRITES:
        x, y, width, height, pivot_x, pivot_y = table[name]
        # The same rounded pivot the solid layer's vertex shader uses.
        pivot_x, pivot_y = math.floor(pivot_x + 0.5), math.floor(pivot_y + 0.5)
        big = atlas[y : y + height, x : x + width]
        for _ in range(3):
            big = scale2x(big)
        baked[name] = [
            bake_frame(big, width, height, pivot_x, pivot_y, 2 * math.pi * i / FRAMES) for i in range(FRAMES)
        ]

    rows = {}
    pen_x, pen_y, shelf = 0, 0, 0
    placed = []
    for name in SPRITES:
        rows[name] = []
        for pixels, frame_x, frame_y in baked[name]:
            height, width = pixels.shape[:2]
            if pen_x + width > SHEET_WIDTH:
                pen_x, pen_y, shelf = 0, pen_y + shelf + 1, 0
            placed.append((pixels, pen_x, pen_y))
            rows[name].append([pen_x, pen_y, width, height, int(frame_x), int(frame_y)])
            pen_x += width + 1
            shelf = max(shelf, height)
    sheet = np.zeros((pen_y + shelf, SHEET_WIDTH, 4), dtype=np.uint8)
    for pixels, x, y in placed:
        sheet[y : y + pixels.shape[0], x : x + pixels.shape[1]] = pixels
    Image.fromarray(sheet).save('assets/rotations.png', optimize=True)

    lines = [
        '// Owns: where each baked rotation sits in assets/rotations.png. Generated by tools/bake-rotations.py.',
        'import type { AtlasSprite } from \'./atlas-table.ts\';',
        '',
        f'export const ROTATION_FRAMES = {FRAMES};',
        '',
        'export const ROTATION_TABLE: Readonly<Record<string, readonly AtlasSprite[]>> = {',
    ]
    for name in SPRITES:
        lines.append(f'  {name}: [')
        lines += [f'    [{", ".join(map(str, row))}],' for row in rows[name]]
        lines.append('  ],')
    lines += ['};', '']
    with open('src/content/rotation-frames.ts', 'w', newline='\n') as out:
        out.write('\n'.join(lines))
    print(f'sheet {SHEET_WIDTH}x{sheet.shape[0]}')


main()
